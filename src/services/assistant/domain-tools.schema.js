// Schema descriptions are part of the model contract, not model-supplied code.
const contract = Object.entries(definitions).map(([tool, shape]) => {
  const object = shape.shape ? shape : shape.innerType();
  const fields = Object.entries(object.shape).map(([key, field]) => `${key}${field.isOptional() ? '?' : ''}`).join(', ');
  return `${tool} {${fields}}: ${descriptions[tool]}`;
}).join('\n');
